"""Alembic environment: synchronous, runs as the OWNER role.

Uses MIGRATION_DATABASE_URL (psycopg2, owner `fnh`), never the app's `fnh_app` URL: the
app role is deliberately unable to ALTER tables or CREATE POLICY. On Fly this runs in the
fnh-api release_command (02-environments.md). RLS policies and partial indexes are always
hand-written; autogenerate does not see them (05-data.md).
Copied from OrderUp backend/migrations/env.py @ 2f86cd8.
"""

from __future__ import annotations

from logging.config import fileConfig

from alembic import context
from sqlalchemy import engine_from_config, pool

from app.core.config import settings
from app.models import Base

config = context.config
config.set_main_option("sqlalchemy.url", settings.MIGRATION_DATABASE_URL)

if config.config_file_name is not None:
    fileConfig(config.config_file_name)

target_metadata = Base.metadata


def run_migrations_offline() -> None:
    context.configure(
        url=settings.MIGRATION_DATABASE_URL,
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
    )
    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    connectable = engine_from_config(
        {"sqlalchemy.url": settings.MIGRATION_DATABASE_URL},
        prefix="sqlalchemy.",
        poolclass=pool.NullPool,
    )
    with connectable.connect() as connection:
        context.configure(connection=connection, target_metadata=target_metadata)
        with context.begin_transaction():
            context.run_migrations()
    connectable.dispose()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
