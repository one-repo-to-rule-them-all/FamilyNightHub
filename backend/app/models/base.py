"""Declarative base and shared column helpers (05-data.md "Conventions").

UUID primary keys generated by Postgres, timestamptz everywhere. Household-scoped tables
carry `household_id` and expose `UNIQUE (id, household_id)` so children can reference
them with a composite FK `(parent_id, household_id)`. Foreign-key checks run without RLS,
so a plain `parent_id` FK would let one household point at another's row; the composite
FK makes that impossible at the database level (ADR-0003, defense in depth).
"""

from __future__ import annotations

import uuid
from datetime import datetime

from sqlalchemy import DateTime, ForeignKey, ForeignKeyConstraint, MetaData, func, text
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

# Deterministic constraint names so migrations and `alembic check` stay stable.
NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_N_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)


def uuid_pk() -> Mapped[uuid.UUID]:
    return mapped_column(
        UUID(as_uuid=True), primary_key=True, server_default=text("gen_random_uuid()")
    )


def created_at() -> Mapped[datetime]:
    return mapped_column(DateTime(timezone=True), server_default=func.now())


def household_fk() -> Mapped[uuid.UUID]:
    return mapped_column(
        UUID(as_uuid=True), ForeignKey("households.id", ondelete="CASCADE"), index=True
    )


def scoped_fk(
    column: str, parent: str, *, ondelete: str | None = None, parent_key: str = "household_id"
) -> ForeignKeyConstraint:
    """Composite FK `(column, household_id) -> parent(id, household_id)`.

    Default is NO ACTION, not RESTRICT: it still blocks a direct delete of a referenced
    parent, but is checked at end of statement, so a household-level cascade succeeds.
    """
    return ForeignKeyConstraint(
        [column, "household_id"], [f"{parent}.id", f"{parent}.{parent_key}"], ondelete=ondelete
    )
